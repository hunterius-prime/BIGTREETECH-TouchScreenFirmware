<#
  Generates TFT/src/User/API/CncDroFont.c: the large readout font of the Turtle CNC build.

  Glyphs "0123456789.-+XYZ" rendered with Windows' Bahnschrift SemiBold SemiCondensed (a DIN-style condensed
  face, like the digits of a DRO), anti-aliased, stored as 4-bit coverage (16 levels, 2 pixels per byte,
  row-major, high nibble first). Digits share one advance (tabular) so values do not jump while they change.

  Usage (Windows PowerShell 7):  ./tools/cnc/make_dro_font.ps1 [-CapHeight 32]
#>
param(
  [int]$CapHeight = 32,
  [string]$Family = 'Bahnschrift SemiBold SemiConden',
  [string]$Out = (Join-Path $PSScriptRoot '..\..\TFT\src\User\API\CncDroFont.c'),
  [string]$Preview
)
$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Drawing

$chars = '0123456789.-+XYZ'

function Render([char]$c, [float]$size) {
  $w = [int]($size * 1.4) + 8; $h = [int]($size * 1.6) + 8
  $bmp = New-Object System.Drawing.Bitmap $w, $h, ([System.Drawing.Imaging.PixelFormat]::Format24bppRgb)
  $g = [System.Drawing.Graphics]::FromImage($bmp)
  $g.Clear([System.Drawing.Color]::Black)
  $g.TextRenderingHint = [System.Drawing.Text.TextRenderingHint]::AntiAlias
  $font = New-Object System.Drawing.Font $Family, $size, ([System.Drawing.FontStyle]::Regular), ([System.Drawing.GraphicsUnit]::Pixel)
  $g.DrawString([string]$c, $font, [System.Drawing.Brushes]::White, 4, 4)
  $g.Dispose(); $font.Dispose()
  $px = New-Object 'int[,]' $h, $w
  for ($y = 0; $y -lt $h; $y++) { for ($x = 0; $x -lt $w; $x++) { $px[$y, $x] = $bmp.GetPixel($x, $y).R } }
  $bmp.Dispose()
  # ink box
  $x0 = $w; $x1 = -1; $y0 = $h; $y1 = -1
  for ($y = 0; $y -lt $h; $y++) { for ($x = 0; $x -lt $w; $x++) { if ($px[$y, $x] -gt 24) {
    if ($x -lt $x0) { $x0 = $x }; if ($x -gt $x1) { $x1 = $x }; if ($y -lt $y0) { $y0 = $y }; if ($y -gt $y1) { $y1 = $y } } } }
  [pscustomobject]@{ c = $c; w = $w; h = $h; px = $px; x0 = $x0; x1 = $x1; y0 = $y0; y1 = $y1 }
}

# font size giving the wanted height of the digit '8'
$probe = Render '8' 100
$size = 100 * $CapHeight / ($probe.y1 - $probe.y0 + 1)
$g8 = Render '8' $size
while (($g8.y1 - $g8.y0 + 1) -gt $CapHeight) { $size -= 0.25; $g8 = Render '8' $size }
while (($g8.y1 - $g8.y0 + 1) -lt $CapHeight) { $size += 0.25; $g8 = Render '8' $size }

$glyphs = foreach ($c in $chars.ToCharArray()) { Render $c $size }
$top = ($glyphs | Where-Object { $_.c -match '[0-9XYZ]' } | Measure-Object y0 -Minimum).Minimum
$base = ($glyphs | Where-Object { $_.c -match '[0-9]' } | Measure-Object y1 -Maximum).Maximum
$H = $base - $top + 1
$digitInk = ($glyphs | Where-Object { $_.c -match '[0-9]' } | ForEach-Object { $_.x1 - $_.x0 + 1 } | Measure-Object -Maximum).Maximum
$digitAdv = $digitInk + 3

$data = New-Object System.Collections.Generic.List[byte]
$table = @()
$previewRows = @()
foreach ($gl in $glyphs) {
  $ink = $gl.x1 - $gl.x0 + 1
  switch -regex ($gl.c) {
    '[0-9]' { $adv = $digitAdv }
    '\.'    { $adv = $ink + 5 }
    '-'     { $adv = $ink + 4 }
    default { $adv = $ink + 2 }
  }
  $left = [int][math]::Floor(($adv - $ink) / 2)
  if ($gl.c -match '[XYZ]') { $left = 0 }  # axis letter sits right in front of its value
  $offset = $data.Count
  for ($y = 0; $y -lt $H; $y++) {
    $row = ''
    for ($x = 0; $x -lt $adv; $x += 2) {
      $n = @(0, 0)
      for ($k = 0; $k -lt 2; $k++) {
        $sx = $gl.x0 + ($x + $k) - $left; $sy = $top + $y
        $v = 0
        if (($x + $k) -lt $adv -and $sx -ge 0 -and $sx -lt $gl.w -and $sy -ge 0 -and $sy -lt $gl.h) { $v = $gl.px[$sy, $sx] }
        $n[$k] = [int][math]::Round($v * 15 / 255)
        $row += ' .:-=+*#%@@@@@@@'[$n[$k]]
      }
      $data.Add([byte](($n[0] -shl 4) -bor $n[1]))
    }
    if ($gl.c -match '[0-9XYZ.-]') { $previewRows += $row }
  }
  $table += [pscustomobject]@{ c = $gl.c; adv = $adv; off = $offset }
}

$lines = @()
$lines += '// Generated by tools/cnc/make_dro_font.ps1 - do not edit by hand.'
$lines += "// Readout font of the Turtle CNC build: ""$chars"" in $Family, $($H) px high"
$lines += '// (digit height), 4-bit coverage, 2 pixels per byte (high nibble first), row-major. Digits are tabular.'
$lines += ''
$lines += '#ifdef TURTLE_CNC'
$lines += ''
$lines += '#include "CncDroFont.h"'
$lines += ''
$lines += 'static const uint8_t cncDroFontData[] = {'
for ($i = 0; $i -lt $data.Count; $i += 24) {
  $chunk = $data.GetRange($i, [math]::Min(24, $data.Count - $i)) | ForEach-Object { '0x{0:X2}' -f $_ }
  $lines += '  ' + ($chunk -join ',') + ','
}
$lines += '};'
$lines += ''
$lines += 'const CNC_DRO_FONT cncDroFont = {'
$lines += "  $H,  // height"
$lines += "  $($table.Count),  // glyph count"
$lines += '  {'
foreach ($t in $table) { $lines += "    {'$($t.c)', $($t.adv), $($t.off)}," }
$lines += '  },'
$lines += '  cncDroFontData,'
$lines += '};'
$lines += ''
$lines += '#endif  // TURTLE_CNC'
Set-Content -Path $Out -Value $lines -Encoding utf8NoBOM

"font size $([math]::Round($size,2)) px, height $H, digit advance $digitAdv, $($data.Count) bytes -> $Out"
if ($Preview) { Set-Content -Path $Preview -Value $previewRows }
